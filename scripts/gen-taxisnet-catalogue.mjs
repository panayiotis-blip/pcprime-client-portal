// Generates src/services/taxisnet/keyCatalogue.ts from the official MoF XSDs.
// The allowed field-key sets must ship in the app bundle so the pre-export
// validator can reject any key the schema wouldn't accept — XSDs themselves
// aren't bundled. Re-run when a new tax-year schema is added:
//   node scripts/gen-taxisnet-catalogue.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const BASE = 'supabase/xsd-tep-ext-2024';
const FORMS = ['epr1m', 'epr1a', 'epr4', 'epr614'];

const enumsIn = (xml) => [...xml.matchAll(/<xsd:enumeration value="([^"]+)"/g)].map((m) => m[1]);

const complexType = (xml, name) => {
  const m = xml.match(new RegExp(`<xsd:complexType name="${name}">([\\s\\S]*?)</xsd:complexType>`));
  return m ? m[1] : '';
};

const out = {};
for (const form of FORMS) {
  const keysXml = readFileSync(`${BASE}/${form}_2024/cy-${form}-2024-keys.xsd`, 'utf8');
  const declXml = readFileSync(`${BASE}/${form}_2024/cy-${form}-2024-declaration.xsd`, 'utf8');

  const flat = enumsIn(complexType(keysXml, `${form}2024KeyValuePairType`));
  const grid = enumsIn(complexType(keysXml, `${form}2024GridKeyValuePairType`));
  // Grid ids are enumerated on the id attribute of the GridSectionType.
  const gridIds = enumsIn(complexType(declXml, `${form}GridSectionType`));

  out[form] = { flat, grid, gridIds };
}

const banner =
  `// AUTO-GENERATED by scripts/gen-taxisnet-catalogue.mjs — do not edit by hand.\n` +
  `// Allowed TaxisNet field keys / grid ids per form, extracted from the official\n` +
  `// Ministry of Finance XSDs in supabase/xsd-tep-ext-2024/. Used by the\n` +
  `// pre-export validator to reject keys the schema would not accept.\n\n`;

const body =
  `export interface FormKeyCatalogue {\n` +
  `  flat: Set<string>;\n  grid: Set<string>;\n  gridIds: Set<string>;\n}\n\n` +
  `const raw: Record<string, { flat: string[]; grid: string[]; gridIds: string[] }> = ${JSON.stringify(out, null, 2)};\n\n` +
  `export const KEY_CATALOGUE: Record<string, FormKeyCatalogue> = Object.fromEntries(\n` +
  `  Object.entries(raw).map(([form, c]) => [form, {\n` +
  `    flat: new Set(c.flat), grid: new Set(c.grid), gridIds: new Set(c.gridIds),\n` +
  `  }]),\n);\n`;

writeFileSync('src/services/taxisnet/keyCatalogue.ts', banner + body);
console.log('Wrote src/services/taxisnet/keyCatalogue.ts');
for (const f of FORMS) console.log(`  ${f}: ${out[f].flat.length} flat, ${out[f].grid.length} grid, ${out[f].gridIds.length} grids`);
